def pillar_circles(frame, color="#000"):
    return [
        f'<circle cx="{fmt(frame(x, y)[0])}" cy="{fmt(frame(x, y)[1])}" r="{fmt(0.3 * frame.scale)}" fill="#fff" stroke="{color}" stroke-width="2"/>'
        for x, y in PILLARS
    ]


def pillar_array_schematic():
    """Channel with the staggered pillars, the boundary conditions and the dimensions."""
    frame = Frame(100, 175, 55)
    x0, y0 = frame(0, 0)
    x1, y1 = frame(8, 2)
    ym = (y0 + y1) / 2
    body = [rectangle(frame, 8, 2)] + rectangle_edges(frame, 8, 2, (VALUE, VALUE, VALUE, ZERO)) + pillar_circles(frame, VALUE)
    for k in range(5):
        y = y0 - 55 * (0.2 + 0.4 * k)
        body.append(f'<line x1="{x0 - 42}" y1="{fmt(y)}" x2="{x0 - 8}" y2="{fmt(y)}" stroke="#000" stroke-width="1.5" marker-end="url(#arrow)"/>')
    body += [text(x0 - 62, ym, f"{U} = 1, {V} = 0", rotate=-90), text(x0 - 80, ym, bname("inlet"), 12, "#666", rotate=-90)]
    body += [text((x0 + x1) / 2, y1 - 12, f"No slip, {U} = {V} = 0"), text((x0 + x1) / 2, y1 - 30, bname("walls"), 12, "#666")]
    body += [text((x0 + x1) / 2, y0 + 22, bname("walls"), 12, "#666")]
    body += [text(x1 + 20, ym, "Stress-free", rotate=90), text(x1 + 38, ym, bname("outlet"), 12, "#666", rotate=90)]
    px, py = frame(3, 1)
    body += [f'<line x1="{fmt(px + 30)}" y1="{fmt(y0 + 62)}" x2="{fmt(px + 0.3 * 55 * 0.7)}" y2="{fmt(py + 0.3 * 55 * 0.7)}" stroke="#000" stroke-width="1" marker-end="url(#arrow)"/>']
    body += [text(px + 36, y0 + 62, "Pillars, no slip, radius 0.3", 13, anchor="start"), text(px + 36, y0 + 78, bname("pillars"), 12, "#666", "start")]
    body += dimension(x0, y0 + 100, x1, y0 + 100, "8", offset_y=20)
    body += dimension(x1 + 70, y0, x1 + 70, y1, "2", offset_x=14, rotate=90)
    body += origin(frame)
    return svg(680, int(y0 + 130), body, "Pillar array: 8 x 2 channel with 8 pillars of radius 0.3, Stokes flow from left to right")


