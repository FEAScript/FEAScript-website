def advection_diffusion_schematic():
    """1D domain [0, 1] with the boundary conditions, the Gaussian source and the advection direction."""
    x0, x1, y = 80, 500, 190

    def px(x):
        return x0 + (x1 - x0) * x

    left, right = f"{U}(0) = 1", f"d{U}/d{italic('x')} = 0"
    body = [f'<line x1="{x0}" y1="{y}" x2="{x1}" y2="{y}" stroke="#000" stroke-width="2"/>']
    body += [dot(x0, y, 5, color=kind(left)), dot(x1, y, 5, color=kind(right))]
    curve = " ".join(f"{fmt(px(k / 200))},{fmt(y - 12 - 90 * math.exp(-200 * (k / 200 - 0.5) ** 2))}" for k in range(201))
    body += [f'<polyline points="{curve}" fill="none" stroke="#000" stroke-width="1.5"/>']
    body += [text(px(0.5) + 34, y - 90, f"Source {italic('D')}({italic('x')})", anchor="start")]
    body += [f'<line x1="{fmt(px(0.15))}" y1="{y - 40}" x2="{fmt(px(0.32))}" y2="{y - 40}" stroke="{FLUX}" stroke-width="2" marker-end="url(#arrow-flux)"/>']
    body += [text(px(0.235), y - 50, "Advection", 13, "#666")]
    body += [text(x0, y + 28, left), text(x0, y + 44, bname("left"), 12, "#666")]
    body += [text(x1, y + 28, right), text(x1, y + 44, bname("right"), 12, "#666")]
    body += dimension(x0, y + 75, x1, y + 75, "1", offset_y=20)
    body += [
        text(
            px(0.5),
            40,
            f"d<tspan dy=\"-6\" font-size=\"11\">2</tspan><tspan dy=\"6\">{U}/d{italic('x')}</tspan>"
            f"<tspan dy=\"-6\" font-size=\"11\">2</tspan><tspan dy=\"6\">&#160;− 10 d{U}/d{italic('x')} = {italic('D')}({italic('x')})</tspan>",
            18,
        )
    ]
    return svg(580, 310, body, "Advection-diffusion in 1D: domain [0, 1], Gaussian source centered at x = 0.5")


