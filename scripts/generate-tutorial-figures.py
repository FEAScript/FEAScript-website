def cavity_schematic():
    no_slip = f"No slip, {U} = {V} = 0"
    sides = ((no_slip, "bottom"), (no_slip, "left"), (f"Moving lid, {U} = 1 m/s, {V} = 0", "top"), (no_slip, "right"))

    def lid(frame):
        _, y1 = frame(0, 2)
        x1, _ = frame(4, 2)
        return [f'<line x1="{fmt(x1 - 120)}" y1="{fmt(y1 - 48)}" x2="{fmt(x1 - 20)}" y2="{fmt(y1 - 48)}" stroke="#000" stroke-width="2" marker-end="url(#arrow)"/>']

    inside = [
        (f"−{italic('μ')}∇<tspan dy=\"-6\" font-size=\"11\">2</tspan><tspan dy=\"6\"><tspan font-weight=\"bold\">u</tspan> + ∇{italic('p')} = 0</tspan>", (2, 1.1)),
        ("∇·<tspan font-weight=\"bold\">u</tspan> = 0", (2, 0.8)),
    ]
    return rect_geometry(4, 2, sides, inside, "Lid-driven cavity: 4 m x 2 m", extra=lid)


PILLARS = [(2, 0.5), (2, 1.5), (3, 1), (4, 0.5), (4, 1.5), (5, 1), (6, 0.5), (6, 1.5)]
