"""Generate the mesh figures of the tutorials, and the schematic of the advection-diffusion tutorial.

The figures follow the style of the other tutorial figures: black line art, sans-serif 15 px labels, boundary
keys in grey 12 px, dashed dimension lines with arrows, and thin grey mesh edges. The 2D meshes use the layout of
gmsh_rect_quad.svg and gmsh_rhom_quad.svg (side names with their boundary keys, origin marker).
The fin's triangle mesh is generated by the FEAScript-core checkout beside this repository (needs Node.js).

    python3 scripts/generate-tutorial-figures.py

The figures are written to tutorials/, beside the tutorial pages.
"""

import json
import math
import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "tutorials")

DEFS = """  <defs>
    <marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse">
      <path d="M0,0 L10,5 L0,10 z" fill="#000"/>
    </marker>
  </defs>"""

MESH_STYLE = 'fill="none" stroke="#000" stroke-width="0.8" stroke-opacity="0.55" stroke-linejoin="round"'


def fmt(value):
    return f"{value:.2f}".rstrip("0").rstrip(".")


def svg(width, height, body, comment):
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" width="{width}" height="{height}" '
        f'font-family="sans-serif" font-size="15" fill="#000">\n  <!-- {comment} -->\n{DEFS}\n'
        + "\n".join("  " + line for line in body)
        + "\n</svg>\n"
    )


def text(x, y, content, size=15, fill="#000", anchor="middle", rotate=None):
    attributes = f'x="{fmt(x)}" y="{fmt(y)}"'
    if size != 15:
        attributes += f' font-size="{size}"'
    if fill != "#000":
        attributes += f' fill="{fill}"'
    if anchor != "start":
        attributes += f' text-anchor="{anchor}"'
    if rotate is not None:
        attributes += f' transform="rotate({rotate} {fmt(x)} {fmt(y)})"'
    return f"<text {attributes}>{content}</text>"


def italic(symbol):
    return f'<tspan font-style="italic">{symbol}</tspan>'


def dimension(x1, y1, x2, y2, content, offset_y=20):
    return [
        f'<line x1="{fmt(x1)}" y1="{fmt(y1)}" x2="{fmt(x2)}" y2="{fmt(y2)}" stroke="#000" stroke-width="1" '
        'stroke-dasharray="4 3" marker-start="url(#arrow)" marker-end="url(#arrow)"/>',
        text((x1 + x2) / 2, (y1 + y2) / 2 + offset_y, content),
    ]


def node(x, y, radius=4, filled=False):
    fill = "#000" if filled else "#fff"
    return f'<circle cx="{fmt(x)}" cy="{fmt(y)}" r="{radius}" fill="{fill}" stroke="#000" stroke-width="1.5"/>'


def structured_mesh_2d(width, height, nx, ny, comment):
    """A width x height rectangle, scaled to 320 px wide, with nx x ny elements (layout of gmsh_rect_quad.svg)."""
    scale = 320 / width
    x0, y0 = 130, 80 + scale * height
    x1, y1 = x0 + scale * width, 80
    lines = []
    for i in range(1, nx):
        x = x0 + (x1 - x0) * i / nx
        lines.append(f'<line x1="{fmt(x)}" y1="{fmt(y0)}" x2="{fmt(x)}" y2="{fmt(y1)}"/>')
    for j in range(1, ny):
        y = y0 + (y1 - y0) * j / ny
        lines.append(f'<line x1="{fmt(x0)}" y1="{fmt(y)}" x2="{fmt(x1)}" y2="{fmt(y)}"/>')
    xm, ym = (x0 + x1) / 2, (y0 + y1) / 2
    body = [f"<g {MESH_STYLE}>"] + ["  " + line for line in lines] + ["</g>"]
    body += [
        f'<rect x="{fmt(x0)}" y="{fmt(y1)}" width="{fmt(x1 - x0)}" height="{fmt(y0 - y1)}" fill="none" stroke="#000" stroke-width="2"/>'
    ]
    body += [text(xm, y0 + 28, "bottom"), text(xm, y0 + 44, 'boundary "0"', 12, "#666")]
    body += [text(x0 - 14, ym, "left", rotate=-90), text(x0 - 32, ym, 'boundary "1"', 12, "#666", rotate=-90)]
    body += [text(xm, y1 - 10, "top"), text(xm, y1 - 28, 'boundary "2"', 12, "#666")]
    body += [text(x1 + 20, ym, "right", rotate=90), text(x1 + 38, ym, 'boundary "3"', 12, "#666", rotate=90)]
    body += [f'<circle cx="{fmt(x0)}" cy="{fmt(y0)}" r="3"/>', text(x0 - 8, y0 + 20, "(0, 0)", 13, anchor="end")]
    return svg(580, int(y0 + 80), body, comment)


def mesh_1d(length, elements, quadratic, left, right, length_label, comment):
    """A 1D mesh: element end nodes as open circles, midside nodes of quadratic elements as small dots."""
    x0, x1, y = 80, 500, 120
    body = [f'<line x1="{x0}" y1="{y}" x2="{x1}" y2="{y}" stroke="#000" stroke-width="2"/>']
    for i in range(elements):
        if quadratic:
            xm = x0 + (x1 - x0) * (i + 0.5) / elements
            body.append(f'<circle cx="{fmt(xm)}" cy="{y}" r="2"/>')
    body += [node(x0 + (x1 - x0) * i / elements, y) for i in range(elements + 1)]
    body += [text(x0, y - 26, left), text(x0, y - 44, 'boundary "0"', 12, "#666")]
    body += [text(x1, y - 26, right), text(x1, y - 44, 'boundary "1"', 12, "#666")]
    body += dimension(x0, y + 35, x1, y + 35, length_label)
    body += [f'<circle cx="{x0}" cy="{y + 95}" r="3"/>']
    body += [f'<line x1="{x0}" y1="{y + 95}" x2="{x0 + 50}" y2="{y + 95}" stroke="#000" stroke-width="1" marker-end="url(#arrow)"/>']
    body += [text(x0 + 58, y + 100, italic("x"), anchor="start"), text(x0, y + 113, f"{italic('x')} = 0", 12)]
    return svg(580, 240, body, comment)


def advection_diffusion_schematic():
    """1D domain [0, 1] with the boundary conditions, the Gaussian source and the advection direction."""
    x0, x1, y = 80, 500, 190

    def px(x):
        return x0 + (x1 - x0) * x

    body = [f'<line x1="{x0}" y1="{y}" x2="{x1}" y2="{y}" stroke="#000" stroke-width="2"/>', node(x0, y), node(x1, y)]
    curve = " ".join(
        f"{fmt(px(k / 200))},{fmt(y - 12 - 90 * math.exp(-200 * (k / 200 - 0.5) ** 2))}" for k in range(201)
    )
    body += [f'<polyline points="{curve}" fill="none" stroke="#000" stroke-width="1.5"/>']
    body += [text(px(0.5) + 34, y - 90, f"Source {italic('D')}({italic('x')})", anchor="start")]
    body += [f'<line x1="{fmt(px(0.15))}" y1="{y - 40}" x2="{fmt(px(0.32))}" y2="{y - 40}" stroke="#000" stroke-width="1.5" marker-end="url(#arrow)"/>']
    body += [text(px(0.235), y - 50, "Advection", 13, "#666")]
    body += [text(x0, y + 28, f"{italic('u')}(0) = 1"), text(x0, y + 44, 'boundary "0"', 12, "#666")]
    body += [text(x1, y + 28, f"d{italic('u')}/d{italic('x')} = 0"), text(x1, y + 44, 'boundary "1"', 12, "#666")]
    body += dimension(x0, y + 75, x1, y + 75, "1")
    body += [
        text(
            px(0.5),
            40,
            f"d<tspan dy=\"-6\" font-size=\"11\">2</tspan><tspan dy=\"6\">{italic('u')}/d{italic('x')}</tspan>"
            f"<tspan dy=\"-6\" font-size=\"11\">2</tspan><tspan dy=\"6\">&#160;− 10 d{italic('u')}/d{italic('x')} = {italic('D')}({italic('x')})</tspan>",
            18,
        )
    ]
    return svg(580, 310, body, "Advection-diffusion in 1D: domain [0, 1], Gaussian source centered at x = 0.5")


def read_gmsh_2d(file_name):
    """Nodes, 6-node triangles and boundary curves (by physical tag) of a .msh 4.1 ASCII file of P2 triangles."""
    with open(os.path.join(OUTPUT, file_name)) as handle:
        lines = [line.split() for line in handle]
    section = {line[0]: index for index, line in enumerate(lines) if line and line[0].startswith("$")}
    # Physical tag of each curve entity
    counts = [int(value) for value in lines[section["$Entities"] + 1]]
    curve_tags, row = {}, section["$Entities"] + 2 + counts[0]
    for line in lines[row : row + counts[1]]:
        if int(line[7]) > 0:
            curve_tags[int(line[0])] = int(line[8])
    nodes, row = {}, section["$Nodes"] + 2
    while row < section["$EndNodes"]:
        count = int(lines[row][3])
        tags = [int(line[0]) for line in lines[row + 1 : row + 1 + count]]
        for tag, line in zip(tags, lines[row + 1 + count : row + 1 + 2 * count]):
            nodes[tag] = (float(line[0]), float(line[1]))
        row += 1 + 2 * count
    triangles, curves, row = [], {}, section["$Elements"] + 2
    while row < section["$EndElements"]:
        dimension_, entity, element_type, count = (int(value) for value in lines[row])
        for line in lines[row + 1 : row + 1 + count]:
            connectivity = [int(value) for value in line[1:]]
            if element_type == 9:
                triangles.append(connectivity)
            elif element_type == 8 and entity in curve_tags:
                curves.setdefault(curve_tags[entity], []).append(connectivity)
        row += 1 + count
    return nodes, triangles, curves


PILLARS = [(2, 0.5), (2, 1.5), (3, 1), (4, 0.5), (4, 1.5), (5, 1), (6, 0.5), (6, 1.5)]


def pillar_frame(scale, x0, y0):
    """Channel outline and pillars of the pillar array, 8 x 2 with radius 0.3, at scale px per unit."""
    x1, y1 = x0 + 8 * scale, y0 - 2 * scale
    body = [f'<rect x="{x0}" y="{fmt(y1)}" width="{fmt(8 * scale)}" height="{fmt(2 * scale)}" fill="none" stroke="#000" stroke-width="2"/>']
    body += [
        f'<circle cx="{fmt(x0 + scale * x)}" cy="{fmt(y0 - scale * y)}" r="{fmt(0.3 * scale)}" fill="#fff" stroke="#000" stroke-width="2"/>'
        for x, y in PILLARS
    ]
    return body, x1, y1


def pillar_array_schematic():
    """Channel with the staggered pillars, the boundary conditions and the dimensions."""
    scale, x0, y0 = 55, 100, 175
    body, x1, y1 = pillar_frame(scale, x0, y0)
    for k in range(5):
        y = y0 - scale * (0.2 + 0.4 * k)
        body.append(f'<line x1="{x0 - 42}" y1="{fmt(y)}" x2="{x0 - 6}" y2="{fmt(y)}" stroke="#000" stroke-width="1.5" marker-end="url(#arrow)"/>')
    ym = (y0 + y1) / 2
    body += [text(x0 - 62, ym, f"{italic('u')} = 1, {italic('v')} = 0", rotate=-90), text(x0 - 80, ym, 'inlet, boundary "0"', 12, "#666", rotate=-90)]
    body += [text((x0 + x1) / 2, y1 - 10, f"No-slip {italic('u')} = {italic('v')} = 0"), text((x0 + x1) / 2, y1 - 28, 'walls, boundary "1"', 12, "#666")]
    body += [text((x0 + x1) / 2, y0 + 22, 'walls, boundary "1"', 12, "#666")]
    body += [text(x1 + 20, ym, "Stress-free", rotate=90), text(x1 + 38, ym, 'outlet, boundary "2"', 12, "#666", rotate=90)]
    px, py = x0 + scale * 3, y0 - scale * 1
    body += [f'<line x1="{fmt(px + 30)}" y1="{fmt(y0 + 62)}" x2="{fmt(px + 0.3 * scale * 0.7)}" y2="{fmt(py + 0.3 * scale * 0.7)}" stroke="#000" stroke-width="1" marker-end="url(#arrow)"/>']
    body += [text(px + 36, y0 + 62, f"Pillars, no-slip, radius 0.3", 13, anchor="start"), text(px + 36, y0 + 78, 'boundary "3"', 12, "#666", anchor="start")]
    body += dimension(x0, y0 + 100, x1, y0 + 100, "8")
    body += [f'<line x1="{fmt(x1 + 70)}" y1="{y0}" x2="{fmt(x1 + 70)}" y2="{fmt(y1)}" stroke="#000" stroke-width="1" stroke-dasharray="4 3" marker-start="url(#arrow)" marker-end="url(#arrow)"/>']
    body += [text(x1 + 82, ym + 5, "2", anchor="start")]
    body += [f'<circle cx="{x0}" cy="{y0}" r="3"/>', text(x0 - 8, y0 + 20, "(0, 0)", 13, anchor="end")]
    return svg(680, int(y0 + 130), body, "Pillar array: 8 x 2 channel with 8 pillars of radius 0.3, Stokes flow from left to right")


def pillar_array_mesh():
    """The P2 triangle mesh of pillar_triang_quadratic.msh, with the boundary keys."""
    nodes, triangles, curves = read_gmsh_2d("pillar_triang_quadratic.msh")
    scale, x0, y0 = 70, 70, 210

    def point(tag):
        x, y = nodes[tag]
        return f"{fmt(x0 + scale * x)},{fmt(y0 - scale * y)}"

    polygons = [f'<polygon points="{" ".join(point(t[i]) for i in (0, 3, 1, 4, 2, 5))}"/>' for t in triangles]
    body = [f'<g {MESH_STYLE.replace("0.8", "0.5")}>'] + ["  " + line for line in polygons] + ["</g>"]
    for tag in curves:
        for a, b, m in curves[tag]:
            body.append(f'<polyline points="{point(a)} {point(m)} {point(b)}" fill="none" stroke="#000" stroke-width="1.6"/>')
    x1, y1, ym = x0 + 8 * scale, y0 - 2 * scale, y0 - scale
    body += [text(x0 - 14, ym, "inlet", rotate=-90), text(x0 - 32, ym, 'boundary "0"', 12, "#666", rotate=-90)]
    body += [text((x0 + x1) / 2, y1 - 10, "walls"), text((x0 + x1) / 2, y1 - 28, 'boundary "1"', 12, "#666")]
    body += [text(x1 + 20, ym, "outlet", rotate=90), text(x1 + 38, ym, 'boundary "2"', 12, "#666", rotate=90)]
    body += [text((x0 + x1) / 2, y0 + 26, 'walls: boundary "1", pillars: boundary "3"', 12, "#666")]
    body += [f'<circle cx="{x0}" cy="{y0}" r="3"/>', text(x0 - 8, y0 + 20, "(0, 0)", 13, anchor="end")]
    comment = f"Mesh: {len(triangles)} quadratic triangles ({len(nodes)} nodes), read from pillar_triang_quadratic.msh"
    return svg(680, int(y0 + 60), body, comment)


# The fin given by its four corners, and with a point every 0.5 along its sides (the two codes of the tutorial page)
FIN_CORNERS = "{ rectangle: [4, 2] }"
FIN_SEEDED = """(() => {
  const along = (from, to, count) =>
    Array.from({ length: count + 1 }, (_, i) => [
      from[0] + ((to[0] - from[0]) * i) / count,
      from[1] + ((to[1] - from[1]) * i) / count,
    ]);
  return { shape: { start: [0, 0], boundaries: [
    { name: "bottom", to: along([0, 0], [4, 0], 8).slice(1) },
    { name: "right", to: along([4, 0], [4, 2], 4).slice(1) },
    { name: "top", to: along([4, 2], [0, 2], 8).slice(1) },
    { name: "left", to: along([0, 2], [0, 0], 4).slice(1) },
  ] } };
})()"""


def fin_triangle_mesh(geometry, description):
    """The quadratic triangle mesh of the fin, generated by the FEAScript-core checkout
    beside this repository, with the settings of the tutorial page (layout of gmsh_rect_quad.svg)."""
    core = os.path.join(os.path.dirname(ROOT), "FEAScript-core", "src", "index.js")
    script = f"""
import {{ generateTriangleMesh, logSystem }} from "{core}";
logSystem("none");
const mesh = generateTriangleMesh(
  {geometry},
  {{ elementOrder: "quadratic", size: 0.5, minAngle: 30 }},
);
console.log(JSON.stringify({{
  x: Array.from(mesh.nodesXCoordinates),
  y: Array.from(mesh.nodesYCoordinates),
  triangles: mesh.nodalNumbering,
}}));
"""
    output = subprocess.run(["node", "--input-type=module", "-e", script], capture_output=True, check=True, text=True)
    mesh = json.loads(output.stdout.strip().splitlines()[-1])
    scale = 320 / 4
    x0, y0 = 130, 80 + scale * 2
    x1, y1 = x0 + scale * 4, 80

    def point(tag):  # The node numbers of the mesh start at 1
        return f"{fmt(x0 + scale * mesh['x'][tag - 1])},{fmt(y0 - scale * mesh['y'][tag - 1])}"

    # FEAScript order of a quadratic triangle: corners 0, 5, 2 counter-clockwise, middle nodes 3, 4, 1 between them
    polygons = [f'<polygon points="{" ".join(point(t[i]) for i in (0, 3, 5, 4, 2, 1))}"/>' for t in mesh["triangles"]]
    xm, ym = (x0 + x1) / 2, (y0 + y1) / 2
    body = [f"<g {MESH_STYLE}>"] + ["  " + line for line in polygons] + ["</g>"]
    body += [
        f'<rect x="{fmt(x0)}" y="{fmt(y1)}" width="{fmt(x1 - x0)}" height="{fmt(y0 - y1)}" fill="none" stroke="#000" stroke-width="2"/>'
    ]
    body += [text(xm, y0 + 28, "bottom"), text(xm, y0 + 44, 'boundary "0"', 12, "#666")]
    body += [text(x1 + 20, ym, "right", rotate=90), text(x1 + 38, ym, 'boundary "1"', 12, "#666", rotate=90)]
    body += [text(xm, y1 - 10, "top"), text(xm, y1 - 28, 'boundary "2"', 12, "#666")]
    body += [text(x0 - 14, ym, "left", rotate=-90), text(x0 - 32, ym, 'boundary "3"', 12, "#666", rotate=-90)]
    body += [f'<circle cx="{fmt(x0)}" cy="{fmt(y0)}" r="3"/>', text(x0 - 8, y0 + 20, "(0, 0)", 13, anchor="end")]
    comment = (
        f"2D fin: {len(mesh['triangles'])} quadratic triangles ({len(mesh['x'])} nodes), generated by "
        f"FEAScript from {description} with size 0.5 and minAngle 30, as on the tutorial page"
    )
    return svg(580, int(y0 + 80), body, comment)


