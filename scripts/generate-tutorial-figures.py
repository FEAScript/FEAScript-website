"""Generate the schematics and mesh figures of the tutorials.

The figures use the shared style of the FEAScript figures (scripts/figure_style.py, the same file as in
FEAScript-documentation): boundaries colored by the type of their condition, boundary names as they are written in
code, Roboto Mono labels and a sunken fill for the domain. feascript-website.js inlines them in the pages so that
they follow the light and dark themes.

The fin's triangle meshes are generated by the FEAScript-core checkout beside this repository (needs Node.js); the
Gmsh meshes are read from the .msh files in tutorials/.

    python3 scripts/generate-tutorial-figures.py

The figures are written to tutorials/, beside the tutorial pages.
"""

