def rect_geometry(width, height, sides, inside, comment, extra=None):
    """A width x height rectangle with a condition on each side: sides = ((condition, name), ...) in the order
    bottom, left, top, right, colored by the type of the condition."""
    scale = min(320 / width, 200 / height)
    frame = Frame(160, 80 + scale * height, scale)
    x0, y0 = frame(0, 0)
    x1, y1 = frame(width, height)
    xm, ym = (x0 + x1) / 2, (y0 + y1) / 2
    body = [rectangle(frame, width, height)]
    body += rectangle_edges(frame, width, height, [kind(condition) for condition, _ in sides])
    if extra:
        body += extra(frame)
    for (condition, key), side, (x, y) in zip(sides, ("bottom", "left", "top", "right"), ((xm, y0), (x0, ym), (xm, y1), (x1, ym))):
        body += label(x, y, condition, bname(key), side)
    for content, (x, y) in inside:
        body.append(text(*frame(x, y), content))
    body += origin(frame)
    body += dimension(x0, y0 + 70, x1, y0 + 70, f"{fmt(width)} m", offset_y=20)
    body += dimension(x0 - 80, y0, x0 - 80, y1, f"{fmt(height)} m", offset_x=-10, rotate=-90)
    return svg(int(x1 + 120), int(y0 + 110), body, comment)


def mesh_figure(polygons, outline_points, sides, comment, extra=(), width=320, bottom=70):
    """A 2D mesh (polygons in model coordinates) scaled to width px, with its boundary names.

    sides: (x, y, name, side) in model coordinates; side is bottom, left, top, right or (angle, normal)."""
    xs = [x for x, _ in outline_points]
    ys = [y for _, y in outline_points]
    scale = width / (max(xs) - min(xs))
    height = scale * (max(ys) - min(ys))
    frame = Frame(130 - scale * min(xs), 80 + height + scale * min(ys), scale)
    body = gmsh_mesh(frame, polygons) + [outline([frame(x, y) for x, y in outline_points])]
    body += list(extra(frame)) if callable(extra) else []
    for x, y, key, side in sides:
        px, py = frame(x, y)
        if isinstance(side, tuple):
            angle, (nx, ny) = side
            body.append(text(px + 22 * nx, py + 22 * ny, bname(key), rotate=angle))
        else:
            body += label(px, py, bname(key), "", side)
    body += [dot(*frame(0, 0)), text(frame(0, 0)[0] - 8, frame(0, 0)[1] + 20, "(0, 0)", 13, anchor="end")]
    return svg(int(130 + scale * (max(xs) - min(xs)) + 110), int(80 + height + bottom), body, comment)


def grid_polygons(width, height, nx, ny):
    return [
        [(width * i / nx, height * j / ny), (width * (i + 1) / nx, height * j / ny), (width * (i + 1) / nx, height * (j + 1) / ny), (width * i / nx, height * (j + 1) / ny)]
        for i in range(nx)
        for j in range(ny)
    ]


RECT = [(0, 0), (4, 0), (4, 2), (0, 2)]
RECT_SIDES = [(2, 0, "bottom", "bottom"), (0, 1, "left", "left"), (2, 2, "top", "top"), (4, 1, "right", "right")]


def structured_mesh_2d(nx, ny, comment):
    return mesh_figure(grid_polygons(4, 2, nx, ny), RECT, RECT_SIDES, comment)


def mesh_1d(length_label, elements, quadratic, left, right, comment):
    """A 1D mesh: element end nodes as open circles, midside nodes of quadratic elements as small dots, and the
    boundary nodes in the colors of their conditions."""
    x0, x1, y = 80, 500, 120
    body = [f'<line x1="{x0}" y1="{y}" x2="{x1}" y2="{y}" stroke="#000" stroke-width="2"/>']
    for i in range(elements):
        if quadratic:
            body.append(dot(x0 + (x1 - x0) * (i + 0.5) / elements, y, 2))
    body += [dot(x0 + (x1 - x0) * i / elements, y, 4, filled=False) for i in range(elements + 1)]
    body += [dot(x0, y, 5, color=kind(left)), dot(x1, y, 5, color=kind(right))]
    body += [text(x0, y - 26, left), text(x0, y - 44, bname("left"), 12, "#666")]
    body += [text(x1, y - 26, right), text(x1, y - 44, bname("right"), 12, "#666")]
    body += dimension(x0, y + 35, x1, y + 35, length_label, offset_y=20)
    body += [dot(x0, y + 95), f'<line x1="{x0}" y1="{y + 95}" x2="{x0 + 50}" y2="{y + 95}" stroke="#000" stroke-width="1" marker-end="url(#arrow)"/>']
    body += [text(x0 + 58, y + 100, italic("x"), anchor="start"), text(x0, y + 113, f"{italic('x')} = 0", 12)]
    return svg(580, 240, body, comment)


